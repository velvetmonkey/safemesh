def run_case(check: Path, report: str | None, mutate=None, command=None):
    with tempfile.TemporaryDirectory() as private:
        path = Path(private) / "report.md"
        if report is not None:
            path.write_text(mutate(report) if mutate else report)
        args = [sys.executable, str(check), "--input", str(path)]
        if command:
            args += ["--benchmark-command", sys.executable, str(command)]
        return subprocess.run(args, text=True, capture_output=True)


def replace_once(source: str, old: str, new: str) -> str:
    assert source.count(old) == 1, (old, source.count(old))
    return source.replace(old, new)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", type=Path, default=Path(__file__).with_name("check-retention-budget.py"))
    args = parser.parse_args()
    check = args.check.resolve()
    failures = []
    cases = [
        ("T1", MEASURED_REPORT, None, False, None),
        ("T2", MEASURED_REPORT, lambda s: replace_once(s, "| gcounter | 10000 | 10.3 ms |", "| gcounter | 10000 | 500.1 ms |"), True, "gcounter 10000 restart"),
        ("T3", MEASURED_REPORT, lambda s: replace_once(s, "| utf8-orset | 10000 | 14.1 ms | 5.3 MiB |", "| utf8-orset | 10000 | 14.1 ms | 64.1 MiB |"), True, "utf8-orset 10000 peak RSS"),
        ("T5", MEASURED_REPORT, lambda s: replace_once(s, "680118 | 68.0 |", "680118 | 128.1 |"), True, "utf8-orset 10000 disk bytes/record"),
        ("T6", MEASURED_REPORT, lambda s: replace_once(s, "| gcounter | 1000 | 4.1 ms | 2.7 MiB | 58120 | 58.1 | 3.8 ms | 2.7 MiB |\n", ""), True, "ROWS"),
        ("T7", "", None, True, "ROWS"),
        ("T9", MEASURED_REPORT, lambda s: replace_once(s, "58.1 | 3.8 ms | 2.7 MiB |", "58.1 | 500.1 ms | 2.7 MiB |"), True, "gcounter 1000 restart after migration:"),
        ("T10", MEASURED_REPORT, lambda s: replace_once(s, "58.1 | 3.8 ms | 2.7 MiB |", "58.1 | 3.8 ms | 64.1 MiB |"), True, "gcounter 1000 peak RSS after migration:"),
        ("T11", MEASURED_REPORT, lambda s: replace_once(s, "| 110 | 1.9x | 10.09 ms | 14.47 ms |", "| 256.1 | 1.9x | 10.09 ms | 14.47 ms |"), True, "gcounter 1000 after-append bytes written/record:"),
        ("T12", MEASURED_REPORT, lambda s: replace_once(s, "| 110 | 1.9x | 10.09 ms | 14.47 ms |", "| 110 | 1.9x | 50.01 ms | 14.47 ms |"), True, "gcounter 1000 after-append median append:"),
    ]
    for name, report, mutate, red, needle in cases:
        result = run_case(check, report, mutate)
        ok = (result.returncode != 0 if red else result.returncode == 0)
        if needle:
            ok = ok and needle in result.stdout
        print(f"{name} {'PASS' if ok else 'FAIL'}: exit {result.returncode}")
        if not ok:
            failures.append(name)
    absent = run_case(check, None)
    if absent.returncode == 0 or "ROWS 0" not in absent.stdout:
        print(f"T7 absent FAIL: exit {absent.returncode}")
        failures.append("T7 absent")
    else:
        print(f"T7 absent PASS: exit {absent.returncode}")
    with tempfile.TemporaryDirectory() as private:
        stub = Path(private) / "exit7.py"
        stub.write_text("import sys; sys.exit(7)\n")
        result = run_case(check, MEASURED_REPORT, command=stub)
        ok = result.returncode != 0 and "benchmark exit 7" in result.stdout
        print(f"T8 {'PASS' if ok else 'FAIL'}: exit {result.returncode}")
        if not ok:
            failures.append("T8")
    return int(bool(failures))


if __name__ == "__main__":
    sys.exit(main())
